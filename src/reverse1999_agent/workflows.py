STORY_PROMPT = """
目标：持续推进常驻主线剧情。
优先顺序：
1. 关闭无害的公告或弹窗，或者从无关的二级界面返回。
2. 进入常驻主线，选择下一个可推进的关卡。不要进入预演、新版本提前体验、活动剧情或特别篇。
正常启动时必须先翻到最早的故事页，再从前往后逐页检查文字。当前页没有“未解锁”就继续
下一页；遇到第一个“未解锁”时，选择它前一个已解锁小章节。培养后恢复时跳过扫描，
直接回到持久化剧情检查点。
3. 出现“跳过”按钮时跳过剧情对白或过场动画。
4. 战斗中开启自动战斗；它通常是右上角第三个战斗按钮。开启后等待战斗自行推进。
5. 胜利或结算后领取奖励，并继续下一段主线。
6. 如果战斗失败，选择 finish，并在 reason 中说明需要培养当前队伍角色。
如果完成过的关卡再次出现，不要重复挑战。返回章节选择页，依据离线常驻主线知识选择
下一章；即使下一章尚未解锁，也要打开它的前置要求，跟随游戏定位到地图上的前置支线，
然后选择高亮的必需支线。有些章节需要多个前置支线，应重复检查直到下一章正式解锁。
只有主线因战斗失败受阻时，才允许进入角色培养流程。
""".strip()


CHARACTER_PROMPT = """
目标：用尽量少的资源有效培养指定角色。
无论当前处于哪个界面，都应先安全地恢复到可识别状态；必要时返回稳定的主界面，
然后打开角色界面，检查画面上可见的等级、升级要求和缺少的资源。
如果缺少金币、经验或材料，进入对应的普通资源关卡，消耗体力并开启自动战斗；
领取奖励后返回角色界面，再次尝试升级。
避免不必要的升级，绝不使用付费货币。不要求一次培养到满级：如果当前资源只能完成
一部分有效提升，就完成这一部分并保存成果。体力不足时先按总计保留2个的规则使用体力道具；
达到指定目标、没有可安全使用的材料和体力道具，或者继续推进需要执行禁止操作时，
选择 finish；部分培养也算本轮有效完成。
“塑造”相当于重复角色突破，只能依赖征集/抽卡所得角色材料，绝不是可刷资源。禁止进入、
点击或尝试“塑造”，看到“塑造详情”或其“材料不足”页面必须立即返回。人物培养只考虑
等级、洞悉以及能够从普通资源关卡安全取得的材料。
如果培养流程由主线战败触发，只能培养最近一次编队界面中已确认属于当前队伍的角色；
不能仅仅因为其他角色看起来更强就培养队外角色。
如果无法确认当前队伍名单，应停止选择角色，不要猜测。
""".strip()


def workflow_prompt(workflow: Workflow, character: str = "", target_level: int | None = None) -> str:
    if workflow is Workflow.STORY:
        task = STORY_PROMPT
    else:
        target = character or "用户指定的角色"
        level = f"，目标等级为{target_level}级" if target_level else "，执行一次有实际作用的培养"
        task = f"{CHARACTER_PROMPT}\n本次指定角色：{target}{level}。"
    return f"{COMMON_POLICY}\n\n{task}"
